# anetbbs/features/i18n.py
"""Shared translation-lookup helpers, backed by the MenuTranslation
table (User.language + MenuTranslation, added in v1.0b2.68).

Originally terminal-menu-only (menu_engine.py had its own inline
query), extended here so the web UI's `t()` Jinja global (see
web_app.py's context processor) shares the same lookup-with-English-
fallback logic instead of maintaining a second copy. menu_engine.py's
_apply_menu_translations() now calls get_translations() from here too.

Both callers agree on one convention: 'en' (or no language set at
all) is the common case and does zero queries -- MenuTranslation rows
only ever need to exist for non-English overrides.
"""
import re

from ..models import MenuTranslation


def current_language():
    """Account preference wins; anonymous visitors keep their own selection."""
    from flask import has_request_context, request, session
    from flask_login import current_user
    if not has_request_context():
        return 'en'
    if current_user.is_authenticated:
        return getattr(current_user, 'language', None) or 'en'
    language = session.get('language')
    if language:
        return language
    # The preference cookie contains no authentication state. Ignore unknown
    # values rather than allowing a client to select arbitrary catalogue names.
    language = request.cookies.get('anetbbs_language')
    return language if language in ('en', 'es') else 'en'


def translate(key, default='', *, _language=None, **values):
    """Translate UI text with one catalogue query per non-English request.

    Keep missing defaults out of the cache: two callers may use the same
    missing key with different source text. Named interpolation happens before
    Jinja's ordinary HTML escaping; translations are never marked as safe.
    """
    from flask import g, has_app_context, has_request_context
    source = default or key
    lang = current_language() if _language is None else _language
    text = source
    if lang != 'en' and has_request_context():
        catalogues = g.setdefault('_i18n_catalogues', {})
        if lang not in catalogues:
            catalogues[lang] = {
                row.key: row.text
                for row in MenuTranslation.query.filter_by(lang=lang).all()
            }
        text = catalogues[lang].get(key, source)
    elif lang != 'en' and has_app_context():
        text = get_translation(lang, key, source)
    if values:
        try:
            return text.format(**values)
        except (KeyError, IndexError, ValueError, AttributeError, TypeError):
            # A malformed SysOp override must not break the underlying flow.
            return source.format(**values)
    return text


def terminal_label(session, key, source, **values):
    """Translate labels for native sessions and lightweight adapters."""
    translator = getattr(session, '_terminal_text', None)
    if translator is not None:
        return translator(key, source, **values)
    language = (getattr(session, 'user', None) or {}).get('language', 'en')
    text = DEFAULT_TRANSLATIONS.get(language, {}).get(key, source)
    return text.format(**values) if values else text


class FormTranslations:
    """WTForms' existing gettext adapter, backed by the same catalogue."""
    _keys = {
        'This field is required.': 'validation.required',
        'Invalid input.': 'validation.invalid',
        'Invalid email address.': 'validation.email',
        'Not a valid choice.': 'validation.choice',
        'Invalid Choice: could not coerce.': 'validation.choice',
        'Not a valid integer value.': 'validation.integer',
        'Not a valid date value.': 'validation.date',
        'Field must be equal to %(other_name)s.': 'validation.equal',
        'Field must be between %(min)d and %(max)d characters long.': 'validation.length_range',
        'Field must be at least %(min)d character long.': 'validation.length_min_one',
        'Field must be at least %(min)d characters long.': 'validation.length_min',
        'Field cannot be longer than %(max)d character.': 'validation.length_max_one',
        'Field cannot be longer than %(max)d characters.': 'validation.length_max',
        'Field must be exactly %(max)d character long.': 'validation.length_exact_one',
        'Field must be exactly %(max)d characters long.': 'validation.length_exact',
    }

    def gettext(self, string):
        key = self._keys.get(string)
        text = translate(key, string) if key else string
        if '%(' in string:
            # WTForms interpolates after gettext returns. Check the override
            # here so a mistyped mapping cannot turn a validation error into
            # a server error. Consume %% before looking for mapping names.
            pattern = r'%(?:%|\(([^)]+)\))'
            required = {name for name in re.findall(pattern, string) if name}
            supplied = {name for name in re.findall(pattern, text) if name}
            if supplied != required:
                return string
            try:
                text % {name: '' if name == 'other_name' else 0 for name in required}
            except (KeyError, TypeError, ValueError, OverflowError):
                return string
        return text

    def ngettext(self, singular, plural, n):
        return self.gettext(singular if n == 1 else plural)


def get_translations(lang, keys):
    """Batched lookup: returns {key: text} for every MenuTranslation
    row that exists for `lang` among `keys`. A key with no row simply
    isn't in the returned dict -- callers fall back to their own
    source text, same convention MenuTranslation's own docstring
    describes. Returns {} outright for 'en'/a falsy lang/no keys,
    without touching the database. Must be called inside an app
    context."""
    if not lang or lang == 'en' or not keys:
        return {}
    rows = (MenuTranslation.query
           .filter_by(lang=lang)
           .filter(MenuTranslation.key.in_(list(keys)))
           .all())
    return {r.key: r.text for r in rows}


def get_translation(lang, key, default):
    """Single-key lookup with fallback -- for callers (the web UI's
    t() Jinja global) whose call sites are scattered across templates
    rather than naturally batchable the way one menu render's title +
    item labels are. Prefer get_translations() directly for any caller
    that already has several keys to resolve together."""
    if not lang or lang == 'en':
        return default
    return get_translations(lang, [key]).get(key, default)


